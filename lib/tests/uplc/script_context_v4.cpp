/**
 * \brief Builds a script context of kTxCbor with every allocation failing in turn until it succeeds.
 *
 * \return The number of failed attempts.
 */
static int
sweep_context_allocations(const uint64_t* sub_tx_index, const cardano_redeemer_tag_t tag, const uint64_t index)
{
  cardano_transaction_t* tx       = decode_tx(kTxCbor);
  cardano_utxo_list_t*   utxos    = decode_utxos(kUtxosCbor);
  cardano_redeemer_t*    redeemer = find_redeemer(tx, sub_tx_index, tag, index);
  cardano_plutus_data_t* datum    = decode_data(kSpendDatum);
  cardano_error_t        result   = CARDANO_ERROR_GENERIC;
  int                    limit    = 0;

  for (; result != CARDANO_SUCCESS; ++limit)
  {
    cardano_plutus_data_t* context = NULL;

    reset_allocators_run_count();
    set_malloc_limit(limit);
    cardano_set_allocators(fail_malloc_at_limit, realloc, free);

    result = cardano_uplc_int_build_script_context_v4(tx, sub_tx_index, utxos, &kSlotConfig, redeemer, datum, &context);

    cardano_set_allocators(malloc, realloc, free);
    reset_limited_malloc();

    EXPECT_EQ(context == nullptr, result != CARDANO_SUCCESS);

    cardano_plutus_data_unref(&context);
  }

  cardano_plutus_data_unref(&datum);
  cardano_redeemer_unref(&redeemer);
  cardano_utxo_list_unref(&utxos);
  cardano_transaction_unref(&tx);

  return limit - 1;
}

/**
 * \brief Builds a TxInfo of kTxCbor with every allocation failing in turn until it succeeds.
 *
 * \return The number of failed attempts.
 */
static int
sweep_tx_info_allocations(const uint64_t* sub_tx_index)
{
  cardano_transaction_t* tx     = decode_tx(kTxCbor);
  cardano_utxo_list_t*   utxos  = decode_utxos(kUtxosCbor);
  cardano_error_t        result = CARDANO_ERROR_GENERIC;
  int                    limit  = 0;

  for (; result != CARDANO_SUCCESS; ++limit)
  {
    cardano_plutus_data_t* tx_info = NULL;

    reset_allocators_run_count();
    set_malloc_limit(limit);
    cardano_set_allocators(fail_malloc_at_limit, realloc, free);

    result = cardano_uplc_int_build_tx_info_v4(tx, sub_tx_index, utxos, &kSlotConfig, &tx_info);

    cardano_set_allocators(malloc, realloc, free);
    reset_limited_malloc();

    EXPECT_EQ(tx_info == nullptr, result != CARDANO_SUCCESS);

    cardano_plutus_data_unref(&tx_info);
  }

  cardano_utxo_list_unref(&utxos);
  cardano_transaction_unref(&tx);

  return limit - 1;
}

