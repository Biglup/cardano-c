/**
 * \brief Decodes a hex-encoded CBOR transaction.
 */
static cardano_transaction_t*
decode_tx(const char* hex)
{
  cardano_cbor_reader_t* reader = cardano_cbor_reader_from_hex(hex, strlen(hex));
  cardano_transaction_t* tx     = NULL;

  EXPECT_EQ(cardano_transaction_from_cbor(reader, &tx), CARDANO_SUCCESS);

  cardano_cbor_reader_unref(&reader);

  return tx;
}

/**
 * \brief Decodes a hex-encoded CBOR array of UTxOs.
 */
static cardano_utxo_list_t*
decode_utxos(const char* hex)
{
  cardano_cbor_reader_t* reader = cardano_cbor_reader_from_hex(hex, strlen(hex));
  cardano_utxo_list_t*   list   = NULL;
  int64_t                length = 0;

  EXPECT_EQ(cardano_utxo_list_new(&list), CARDANO_SUCCESS);
  EXPECT_EQ(cardano_cbor_reader_read_start_array(reader, &length), CARDANO_SUCCESS);

  for (int64_t i = 0; i < length; ++i)
  {
    cardano_utxo_t* utxo = NULL;

    EXPECT_EQ(cardano_utxo_from_cbor(reader, &utxo), CARDANO_SUCCESS);
    EXPECT_EQ(cardano_utxo_list_add(list, utxo), CARDANO_SUCCESS);

    cardano_utxo_unref(&utxo);
  }

  cardano_cbor_reader_unref(&reader);

  return list;
}

/**
 * \brief Decodes hex-encoded CBOR plutus data.
 */
static cardano_plutus_data_t*
decode_data(const char* hex)
{
  cardano_cbor_reader_t* reader = cardano_cbor_reader_from_hex(hex, strlen(hex));
  cardano_plutus_data_t* data   = NULL;

  EXPECT_EQ(cardano_plutus_data_from_cbor(reader, &data), CARDANO_SUCCESS);

  cardano_cbor_reader_unref(&reader);

  return data;
}

